// pack.mjs — regenerate main.ts with entry.png embedded as base64.
//
// The publishing channel for this repo accepts UTF-8 text files only, so the
// binary entry.png cannot ship as a file. Instead, main.ts carries the image
// as an embedded base64 constant and decodes it at run time, writing the
// exact bytes to the output path.
//
// Usage: node pack.mjs   (run after re-rendering entry.png with draw.py)

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(fileURLToPath(import.meta.url));
const png = readFileSync(join(root, 'entry.png'));
const base64 = png.toString('base64');

// Wrap at 100 chars per line; Buffer.from(..., 'base64') ignores whitespace.
const wrapped = base64.match(/.{1,100}/g).join('\n');

const main = `// GENERATED by pack.mjs — do not edit by hand. Re-run \`node pack.mjs\`
// after re-rendering entry.png to regenerate this file.
//
// News-image entry for make.fun competition news-image-20261118.
//
// The artwork (drawn by draw.py from the sources listed in SOURCES.md) is
// embedded below as base64, because the publishing channel for this repo
// accepts text files only. The grader runs this program with no network,
// so it simply decodes the embedded image and writes the exact bytes to
// the output directory: $MAKEFUN_OUTPUT_DIR/entry.png, defaulting to
// /output/entry.png.
//
// Local check:  MAKEFUN_OUTPUT_DIR=out node main.ts

import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const IMAGE_BASE64 = \`
${wrapped}
\`;

const outputDir = process.env.MAKEFUN_OUTPUT_DIR ?? '/output';
mkdirSync(outputDir, { recursive: true });
writeFileSync(join(outputDir, 'entry.png'), Buffer.from(IMAGE_BASE64, 'base64'));
`;

writeFileSync(join(root, 'main.ts'), main);
console.log(`main.ts regenerated: embedded ${png.length} bytes (${base64.length} base64 chars)`);
